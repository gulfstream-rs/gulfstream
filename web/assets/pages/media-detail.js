import { currentSession, jsonRequest, request } from '../core/api.js';
import { config, endpoint, mediaIdFromLocation } from '../core/config.js';
import { escapeHtml, optionMarkup, query, setPage } from '../core/dom.js';
import { formatBitrate, formatBytes, formatDate, formatDuration } from '../core/format.js';
import { badge, confirmAction, metricCard, pageHeader, setBusy, setStatus, table, toast } from '../core/ui.js';

export async function renderMediaDetail() {
  await currentSession();
  const mediaId = mediaIdFromLocation();
  if (!mediaId) throw new Error('Media ID is missing.');
  const [media, jobs] = await Promise.all([
    request(endpoint(config.api.media_item_template, mediaId)),
    request(endpoint(config.api.media_jobs_template, mediaId)),
  ]);
  const renditionRows = media.variants.map((variant) => `<tr><td data-label="Name"><strong>${escapeHtml(variant.name)}</strong></td><td data-label="Resolution">${variant.width} × ${variant.height}</td><td data-label="Bandwidth">${formatBitrate(variant.bandwidth_bps)}</td><td data-label="Codecs">${escapeHtml(variant.codecs)}</td></tr>`);
  const jobRows = jobs.map((job) => `<tr><td data-label="Kind">${escapeHtml(job.kind.replaceAll('_', ' '))}</td><td data-label="Status">${badge(job.status)}</td><td data-label="Attempts">${job.attempts}/${job.maximum_attempts}</td><td data-label="Updated">${formatDate(job.updated_at)}</td><td data-label="Error"><span class="processing-error">${escapeHtml(job.error_message || '—')}</span></td></tr>`);
  const actions = `<button class="button button-primary" type="button" id="watch-button"${media.status !== 'ready' ? ' disabled' : ''}>Watch</button><button class="button" type="button" id="retry-button"${media.status !== 'failed' ? ' disabled' : ''}>Retry processing</button>`;

  setPage(`${pageHeader(media.title, 'Manage metadata, playback, conversion output, and processing history.', actions)}
    ${media.error_message ? `<div class="notice notice-error" role="alert"><strong>Processing error:</strong> ${escapeHtml(media.error_message)}</div>` : ''}
    <div class="metric-grid">
      ${metricCard('Status', media.status, badge(media.status))}
      ${metricCard('Visibility', media.visibility, badge(media.visibility))}
      ${metricCard('Duration', media.duration_ms == null ? '—' : formatDuration(media.duration_ms))}
      ${metricCard('Source size', formatBytes(media.source_size_bytes))}
      ${metricCard('Stored size', formatBytes(media.storage_bytes))}
      ${metricCard('Dimensions', media.width && media.height ? `${media.width} × ${media.height}` : '—')}
    </div>
    <div class="two-column page-section"><section class="card"><div class="card-header"><div><h2>Metadata</h2><p>Changes are applied immediately through the API.</p></div></div><div class="card-body"><form id="edit-form" class="form-grid">
      <label class="field"><span>Title</span><input name="title" value="${escapeHtml(media.title)}" maxlength="${config.limits.maximum_text_field_bytes}" required></label>
      <label class="field"><span>Description</span><textarea name="description" maxlength="${config.limits.maximum_text_field_bytes}">${escapeHtml(media.description)}</textarea></label>
      <label class="field"><span>Visibility</span><select name="visibility">${optionMarkup(config.options.media_visibilities, media.visibility)}</select></label>
      <div class="form-actions"><button class="button button-primary" type="submit">Save changes</button><button class="button button-danger" type="button" id="delete-button">Delete media</button></div><p id="media-status" class="form-status" role="status"></p>
    </form></div></section>
    <aside class="card"><div class="card-header"><div><h2>Source details</h2><p>Immutable ingestion metadata.</p></div></div><div class="card-body"><dl class="detail-list"><dt>Source file</dt><dd>${escapeHtml(media.source_filename)}</dd><dt>MIME type</dt><dd>${escapeHtml(media.source_mime_type || '—')}</dd><dt>SHA-256</dt><dd><code>${escapeHtml(media.sha256 || '—')}</code></dd><dt>Video codec</dt><dd>${escapeHtml(media.video_codec || '—')}</dd><dt>Audio codec</dt><dd>${escapeHtml(media.audio_codec || '—')}</dd><dt>Created</dt><dd>${formatDate(media.created_at)}</dd><dt>Published</dt><dd>${formatDate(media.published_at)}</dd></dl></div></aside></div>
    <section class="page-section"><div><h2>Adaptive renditions</h2><p class="field-hint">Published HLS variants generated by the configured processing profiles.</p></div>${table(['Name', 'Resolution', 'Bandwidth', 'Codecs'], renditionRows, 'No renditions are published yet.')}</section>
    <section class="page-section"><div><h2>Processing history</h2><p class="field-hint">Durable job attempts and errors for this media item.</p></div>${table(['Kind', 'Status', 'Attempts', 'Updated', 'Error'], jobRows, 'No processing jobs have been recorded.')}</section>`, 'Media details');

  const status = query('#media-status');
  const editForm = query('#edit-form');
  editForm.addEventListener('submit', async (event) => {
    event.preventDefault();
    const button = editForm.querySelector('button[type="submit"]');
    try {
      setBusy(button, true, 'Saving…');
      setStatus(status, 'Saving metadata…');
      await request(endpoint(config.api.media_item_template, mediaId), jsonRequest('PATCH', Object.fromEntries(new FormData(editForm))));
      toast('Media metadata saved.');
      setStatus(status, 'Saved.', 'success');
      setBusy(button, false);
    } catch (error) {
      setStatus(status, error.message, 'error');
      setBusy(button, false);
    }
  });

  query('#watch-button').addEventListener('click', async () => {
    try {
      setStatus(status, 'Preparing secure playback…');
      const token = await request(endpoint(config.api.media_playback_token_template, mediaId), { method: 'POST' });
      window.location.assign(token.watch_url);
    } catch (error) { setStatus(status, error.message, 'error'); }
  });
  query('#retry-button').addEventListener('click', async () => {
    try {
      setStatus(status, 'Queueing a new processing attempt…');
      await request(endpoint(config.api.media_retry_template, mediaId), { method: 'POST' });
      toast('Processing retry queued.');
      window.location.reload();
    } catch (error) { setStatus(status, error.message, 'error'); }
  });
  query('#delete-button').addEventListener('click', async () => {
    const confirmed = await confirmAction('Delete media', 'Delete this media and all generated streaming assets? This action cannot be undone.');
    if (!confirmed) return;
    try {
      setStatus(status, 'Queueing deletion…');
      await request(endpoint(config.api.media_item_template, mediaId), { method: 'DELETE' });
      window.location.assign(config.routes.media);
    } catch (error) { setStatus(status, error.message, 'error'); }
  });
}
